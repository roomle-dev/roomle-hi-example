import { DEMO_PROXY_URL } from './planner.ts';

export type Layout = Record<string, unknown>;

interface LayoutPlanner {
  extended: {
    getExternalObjectGroups(): Promise<{ id: string }[]>;
    removeExternalObject(id: string): Promise<unknown>;
    loadExternalObjectGroupLayout(
      layout: Layout,
      layoutType: string,
      options: { findFreeSpaceInPlan: boolean }
    ): Promise<unknown>;
  };
}

// The AI endpoint answers no CORS preflight, so the request goes through the demo proxy.
// The placeholder credentials keep the proxy from forwarding its own HOMAG credentials.
export const AI_KITCHEN_GENERATION_URL = `${DEMO_PROXY_URL}?${new URLSearchParams(
  {
    url: 'v1/generate?subscription-key=06c920100e1645cd8d8095366d9a48d1',
    baseUrl: 'https://apim-aiplanner-ki-stage.azure-api.net/',
    subscriptionId: 'a',
    apiKey: 'b',
  }
)}`;

// The default "idm" catalogue plans with articles the nobilia demo library does not contain.
const AI_KITCHEN_GENERATION_REQUEST = {
  metaData: { catalogue: { id: 'elements' } },
};

const isLayout = (value: unknown): value is Layout =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

/** A kitchen layout generated by the AI kitchen generation. */
export const fetchAiKitchenLayout = async (signal: AbortSignal) => {
  const response = await fetch(AI_KITCHEN_GENERATION_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(AI_KITCHEN_GENERATION_REQUEST),
    signal,
  });
  if (!response.ok) {
    throw new Error(`Kitchen generation failed with status ${response.status}`);
  }
  return (await response.json()) as Layout;
};

/** The layout of a JSON file's `text`; null, with the reason in the console, for anything but a JSON object. */
export const parseLayout = (text: string): Layout | null => {
  try {
    const layout: unknown = JSON.parse(text);
    if (isLayout(layout)) {
      return layout;
    }
    console.error('The layout JSON must be an object');
  } catch (error) {
    console.error('The layout JSON cannot be parsed', error);
  }
  return null;
};

/** The layout of a JSON file the user selects; null when the selection is cancelled or invalid. */
export const selectLayoutFile = () =>
  new Promise<Layout | null>((resolve) => {
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = 'application/json,.json';
    input.style.display = 'none';
    input.addEventListener(
      'cancel',
      () => {
        input.remove();
        resolve(null);
      },
      { once: true }
    );
    input.addEventListener(
      'change',
      async () => {
        const file = input.files?.[0];
        input.remove();
        resolve(file ? parseLayout(await file.text()) : null);
      },
      { once: true }
    );
    document.body.appendChild(input);
    input.click();
  });

export const removeExternalObjectGroups = async (planner: LayoutPlanner) => {
  for (const group of await planner.extended.getExternalObjectGroups()) {
    await planner.extended.removeExternalObject(group.id);
  }
};

/** Loads the article `layout` into the plan, where it finds free space. */
export const loadLayout = (planner: LayoutPlanner, layout: Layout) =>
  planner.extended.loadExternalObjectGroupLayout(layout, 'nobila', {
    findFreeSpaceInPlan: true,
  });
